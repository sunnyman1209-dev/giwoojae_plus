def sq(s):
    return re.sub(r"[\s·()\[\]./-]", "", str(s)).lower()


def ans_text(it):
    if it["t"] == "4지선다":
        return f"{C[it['ans']]} {it['choices'][it['ans']]}"
    if it["t"] == "진위형":
        return it["ans"]
    return it["ansText"]


def bank():
    return json.loads((Q / "docs" / "data" / "questions.json").read_text(encoding="utf-8"))["questions"]


def overlap():
    """make_batch.py와 같은 겹침 검사: 정답 글자 같음 / 지문+정답 2-gram 유사도 0.45 이상 (문제은행 전체와 이 묶음 안)."""
    qs = [q for q in bank() if not str(q["id"]).startswith("th|")]
    warn = []

    def grams(s):
        s = sq(s)
        return {s[i:i + 2] for i in range(len(s) - 1)}
    others = [(o["id"], o["stem"], o.get("ansText", "")) for o in qs] + [(i["id"], i["stem"], ans_text(i)) for i in ITEMS]
    for it in ITEMS:
        a = ans_text(it)
        a0 = re.sub(r"^[①②③④]\s*", "", a)
        g = grams(it["stem"] + a)
        for oid, ostem, oans in others:
            if oid == it["id"]:
                continue
            if it["t"] != "진위형" and sq(a0) and sq(a0) == sq(re.sub(r"^[①②③④]\s*", "", oans)):
                warn.append(f"{it['id']} 정답이 {oid}와 같음: {ostem[:60]} / {oans}")
            go = grams(ostem + oans)
            if g and go:
                j = len(g & go) / len(g | go)
                if j >= 0.45:
                    warn.append(f"{it['id']} 지문 유사도 {j:.2f} {oid}: {ostem[:60]} / {oans}")
    return warn


